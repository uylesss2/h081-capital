// Writes solana/programs/rep_registry/src/generated/vk.rs (the reputation verifying key) and nothing else.
// stipend_pool's vk.rs and scripts/gen-solana-vk.mjs are never touched (do NOT run `npm run solana:vk` after a dev
// setup: it would overwrite the pool's ceremony keys with dev ones).
//
//   node scripts/gen-rep-vk.mjs                       from build/circuits/reputation/reputation.vkey.json (a DEV setup:
//                                                     REPUTATION_VK_IS_DEV = true, which the mainnet build refuses)
//   node scripts/gen-rep-vk.mjs --ceremony <vkey>     from a ceremony export (docs/ceremony/reputation/reputation.vkey.json);
//                                                     REPUTATION_VK_IS_DEV = false
//   ... --check                                       writes nothing; exits 1 when the committed vk.rs differs
// Output is deterministic and records the sha256 of the source vkey JSON.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const out = join(root, 'solana', 'programs', 'rep_registry', 'src', 'generated', 'vk.rs');
const args = process.argv.slice(2);
const check = args.includes('--check');
const ci = args.indexOf('--ceremony');
const ceremony = ci >= 0 ? resolve(args[ci + 1] ?? '') : undefined;
const src = ceremony ?? join(root, 'build', 'circuits', 'reputation', 'reputation.vkey.json');
const NPUBLIC = 13;

if (!existsSync(src)) { console.error(`gen-rep-vk: ${src} not found (build and set up the reputation circuit first)`); process.exit(2); }
const raw = readFileSync(src);
const vk = JSON.parse(raw.toString('utf8'));
if (vk.protocol !== 'groth16' || vk.curve !== 'bn128') throw new Error('not a bn128 groth16 key');
if (vk.nPublic !== NPUBLIC || vk.IC.length !== NPUBLIC + 1) throw new Error(`expected ${NPUBLIC} public inputs, got ${vk.nPublic}`);

const be32 = (x) => { const v = BigInt(x); if (v < 0n || v >= 1n << 256n) throw new Error(`out of range: ${x}`); return v.toString(16).padStart(64, '0'); };
const bytesLit = (hex) => {
  const parts = hex.match(/../g).map((b) => `0x${b}`);
  const lines = [];
  for (let i = 0; i < parts.length; i += 16) lines.push('        ' + parts.slice(i, i + 16).join(', ') + ',');
  return `[\n${lines.join('\n')}\n    ]`;
};
const g1 = (p) => { if (String(p[2]) !== '1') throw new Error('G1 point not affine'); return be32(p[0]) + be32(p[1]); };
const g2 = (p) => {
  if (String(p[2][0]) !== '1' || String(p[2][1]) !== '0') throw new Error('G2 point not affine');
  return be32(p[0][1]) + be32(p[0][0]) + be32(p[1][1]) + be32(p[1][0]);
};

const sha = createHash('sha256').update(raw).digest('hex');
let rs = '// @generated by scripts/gen-rep-vk.mjs. Do not edit.\n';
rs += `// source: ${ceremony ? 'ceremony export' : 'DEV single-party setup (build/circuits/reputation)'}; vkey sha256 ${sha}\n`;
rs += 'use crate::groth16::VerifyingKey;\n\n';
rs += `/// true for a dev (single-party) setup: the mainnet build refuses to compile with it.\n`;
rs += `pub const REPUTATION_VK_IS_DEV: bool = ${ceremony ? 'false' : 'true'};\n`;
rs += `pub const REPUTATION_VKEY_SHA256: &str = "${sha}";\n`;
rs += `pub const REPUTATION_NPUBLIC: usize = ${NPUBLIC};\n`;
rs += `pub const REPUTATION_IC: [[u8; 64]; ${NPUBLIC + 1}] = [\n${vk.IC.map((p) => '    ' + bytesLit(g1(p)).replace(/\n/g, '\n    ')).join(',\n')},\n];\n`;
rs += `pub const REPUTATION_VK: VerifyingKey = VerifyingKey {\n`;
rs += `    alpha_g1: ${bytesLit(g1(vk.vk_alpha_1))},\n`;
rs += `    beta_g2: ${bytesLit(g2(vk.vk_beta_2))},\n`;
rs += `    gamma_g2: ${bytesLit(g2(vk.vk_gamma_2))},\n`;
rs += `    delta_g2: ${bytesLit(g2(vk.vk_delta_2))},\n`;
rs += `    ic: &REPUTATION_IC,\n};\n`;

if (check) {
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (cur !== rs) { console.error(`gen-rep-vk --check: ${out} differs from ${src}`); process.exit(1); }
  console.log(`gen-rep-vk --check: ok (${ceremony ? 'ceremony' : 'DEV'} key, sha256 ${sha})`);
} else {
  writeFileSync(out, rs);
  console.log(`wrote ${out} (${ceremony ? 'ceremony' : 'DEV setup'} key, sha256 ${sha})`);
}
