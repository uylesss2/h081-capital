// Turns build/circuits/<name>/<name>.vkey.json into Rust constants for the
// stipend_pool program's Groth16 verifier (alt_bn128 syscalls, big-endian,
// EIP-197 G2 encoding: x.c1 || x.c0 || y.c1 || y.c0), plus the Merkle zero
// hashes (empty leaf keccak256("stipend") mod p, Poseidon up the levels).
// Re-runnable: `node scripts/gen-solana-vk.mjs`. Output is deterministic.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { buildPoseidon } from 'circomlibjs';
import { keccak_256 } from '@noble/hashes/sha3';
import { bytesToHex, utf8ToBytes } from '@noble/hashes/utils';

const root = resolve(import.meta.dirname, '..');
const outDir = join(root, 'solana', 'programs', 'stipend_pool', 'src', 'generated');
const CIRCUITS = [
  ['transact', 8], ['grant', 22], ['spend', 15], ['disclose', 6], ['delegate', 9], ['stream', 13],
];
const FIELD = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;
const LEVELS = 20;

const be32 = (x) => {
  const v = BigInt(x);
  if (v < 0n || v >= 1n << 256n) throw new Error(`out of range: ${x}`);
  return v.toString(16).padStart(64, '0');
};
const bytesLit = (hex) => {
  const parts = hex.match(/../g).map((b) => `0x${b}`);
  const lines = [];
  for (let i = 0; i < parts.length; i += 16) lines.push('        ' + parts.slice(i, i + 16).join(', ') + ',');
  return `[\n${lines.join('\n')}\n    ]`;
};
const g1 = (p) => {
  if (String(p[2]) !== '1') throw new Error('G1 point not affine');
  return be32(p[0]) + be32(p[1]);
};
const g2 = (p) => {
  if (String(p[2][0]) !== '1' || String(p[2][1]) !== '0') throw new Error('G2 point not affine');
  return be32(p[0][1]) + be32(p[0][0]) + be32(p[1][1]) + be32(p[1][0]);
};

mkdirSync(outDir, { recursive: true });
let rs = '// @generated by scripts/gen-solana-vk.mjs from build/circuits/*/*.vkey.json. Do not edit.\n';
rs += 'use crate::groth16::VerifyingKey;\n\n';
for (const [name, n] of CIRCUITS) {
  const vk = JSON.parse(readFileSync(join(root, 'build', 'circuits', name, `${name}.vkey.json`), 'utf8'));
  if (vk.protocol !== 'groth16' || vk.curve !== 'bn128') throw new Error(`${name}: not a bn128 groth16 key`);
  if (vk.nPublic !== n || vk.IC.length !== n + 1) throw new Error(`${name}: expected ${n} public inputs, got ${vk.nPublic}`);
  const N = name.toUpperCase();
  rs += `pub const ${N}_NPUBLIC: usize = ${n};\n`;
  rs += `pub const ${N}_IC: [[u8; 64]; ${n + 1}] = [\n${vk.IC.map((p) => '    ' + bytesLit(g1(p)).replace(/\n {8}/g, '\n        ') + ',').join('\n')}\n];\n`;
  rs += `pub const ${N}_VK: VerifyingKey = VerifyingKey {\n`;
  rs += `    alpha_g1: ${bytesLit(g1(vk.vk_alpha_1))},\n`;
  rs += `    beta_g2: ${bytesLit(g2(vk.vk_beta_2))},\n`;
  rs += `    gamma_g2: ${bytesLit(g2(vk.vk_gamma_2))},\n`;
  rs += `    delta_g2: ${bytesLit(g2(vk.vk_delta_2))},\n`;
  rs += `    ic: &${N}_IC,\n};\n\n`;
}
writeFileSync(join(outDir, 'vk.rs'), rs);

// Merkle zeros: zeros[0] = empty leaf, zeros[i+1] = H(zeros[i], zeros[i]); zeros[LEVELS] = empty root.
const poseidon = await buildPoseidon();
const H = (a, b) => poseidon.F.toObject(poseidon([a, b]));
let z = BigInt('0x' + bytesToHex(keccak_256(utf8ToBytes('stipend')))) % FIELD;
const zeros = [];
for (let i = 0; i <= LEVELS; i++) { zeros.push(z); z = H(z, z); }
let zr = '// @generated by scripts/gen-solana-vk.mjs. Do not edit.\n';
zr += `// zeros[0] = keccak256("stipend") mod p; zeros[i + 1] = Poseidon(zeros[i], zeros[i]); zeros[${LEVELS}] = empty root.\n`;
zr += `pub const ZEROS: [[u8; 32]; ${LEVELS + 1}] = [\n${zeros.map((v) => '    ' + bytesLit(be32(v)) + ',').join('\n')}\n];\n`;
writeFileSync(join(outDir, 'zeros.rs'), zr);
console.log(`wrote ${join(outDir, 'vk.rs')} and zeros.rs (${CIRCUITS.length} keys, ${LEVELS + 1} zeros)`);
